import { readFile, writeFile } from 'node:fs/promises';
import { parseEventsPayload } from '../lib/events.ts';

const inputPath = new URL('../public/data/events.json', import.meta.url);
const outputPath = new URL('../lib/events-snapshot.generated.ts', import.meta.url);

export async function generateEventsSnapshotModule({ inputUrl = inputPath, outputUrl = outputPath } = {}) {
  const payload = parseEventsPayload(JSON.parse(await readFile(inputUrl, 'utf8')));
  const source = `// Generated by scripts/generate-events-snapshot-module.mjs. Do not edit by hand.\nimport type { EventsPayload } from './events';\n\nexport const embeddedEventsPayload = ${JSON.stringify(payload, null, 2)} satisfies EventsPayload;\n`;
  await writeFile(outputUrl, source);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await generateEventsSnapshotModule();
}
